test('pause, resume, stop, finish', () => {
  const t = started()
  t.cli('stage', 'Build')
  t.cli('pause', 'mark')
  assert.deepEqual([t.state().status, t.state().pausedReason], ['paused', 'mark'])
  t.cli('resume')
  assert.deepEqual([t.state().status, t.state().pausedReason], ['running', null])
  t.cli('finish', '--pr', 'https://github.com/o/r/pull/482')
  const s = t.state()
  assert.equal(s.status, 'finished')
  assert.equal(s.stage, 'Ship')
  assert.deepEqual(s.pr, { number: 482, url: 'https://github.com/o/r/pull/482' })
  assert.ok(s.finishedAt)
  const u = started('two')
  u.cli('finish', '--branch', 'lcw/two')
  assert.deepEqual(u.state().pr, { branch: 'lcw/two' })
  const v = started('three')
  v.cli('stop')
  assert.equal(v.state().status, 'stopped')
})

test('runningSince is when the run last started running, kept across stage changes; pausedAt is when it paused, cleared on resume', () => {
  const t = started()
  const at = (ms, ...a) => { process.env.LCW_NOW = String(ms); try { return t.cli(...a) } finally { delete process.env.LCW_NOW } }
  const T = Date.UTC(2026, 10, 19, 9)
  const iso = (min) => new Date(T + min * 60000).toISOString()
  assert.equal(t.state().runningSince, undefined, 'a brainstorm is with you, not running')
  at(T, 'stage', 'Spec')
  at(T + 60000, 'stage', 'Build')
  assert.equal(t.state().runningSince, iso(0))
  at(T + 120000, 'pause', 'human')
  assert.deepEqual([t.state().pausedAt, t.state().runningSince], [iso(2), iso(0)])
  at(T + 180000, 'resume')
  assert.deepEqual([t.state().pausedAt, t.state().runningSince], [null, iso(3)])
})

test('approval puts the Brainstorm question in the state for LCW\'s box; asked again it replaces it; a new stage clears it', () => {
  const t = started()
  assert.equal(t.cli('approval').code, 0)
  const first = t.state().approval
  assert.deepEqual([first.go, first.meaning], [[], ''])
  assert.ok(Number.isFinite(first.at))
  const r = t.cli('approval', 'Go (a)', 'Go (b)', '--meaning', 'build it, with (a) wrapped or (b) short rows')
  assert.equal(r.code, 0)
  assert.deepEqual(t.state().approval.go, ['Go (a)', 'Go (b)'])
  assert.equal(t.state().approval.meaning, 'build it, with (a) wrapped or (b) short rows')
  assert.match(fs.readFileSync(`${t.dir}/ledger.md`, 'utf8'), /approval asked: Go \(a\) \/ Go \(b\)/)
  assert.equal(t.cli('approval', 'a', 'b', 'c', 'd').code, 1, 'at most three Go labels')
  assert.equal(t.cli('approval', 'build it as played back, wrapped').code, 1, 'a label is short; the meaning goes in --meaning')
  assert.equal(t.cli('set', 'approval={"go":["Go"],"at":1}').code, 1, 'only lcw approval sets it')
  t.cli('stage', 'Spec')
  assert.equal(t.state().approval, null)
  assert.equal(t.cli('approval').code, 1, 'only in the Brainstorm')
})
