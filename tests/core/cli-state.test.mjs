test('runningSince is when the run last started running, kept across stage changes; pausedAt is when it paused, cleared on resume', async () => {
  const t = await begin()
  const at = (ms, ...a) => cli(a, { ...t.o, env: { LCW_NOW: String(ms) } })
  const T = Date.UTC(2026, 10, 19, 9)
  const iso = (min) => new Date(T + min * 60000).toISOString()
  assert.equal(t.state().runningSince, undefined, 'a brainstorm is with you, not running')
  await at(T, 'stage', 'Spec')
  await at(T + 60000, 'stage', 'Build')
  assert.equal(t.state().runningSince, iso(0))
  await at(T + 120000, 'pause', 'human')
  assert.deepEqual([t.state().pausedAt, t.state().runningSince], [iso(2), iso(0)])
  await at(T + 180000, 'resume')
  assert.deepEqual([t.state().pausedAt, t.state().runningSince], [null, iso(3)])
})

test('approval puts the Brainstorm question in the state for LCW\'s box; asked again it replaces it; a new stage clears it', async () => {
  const t = await begin()
  assert.equal((await t.cli('approval')).code, 0)
  const first = t.state().approval
  assert.deepEqual([first.go, first.meaning], [[], ''])
  assert.ok(Number.isFinite(first.at))
  const bare = await t.cli('approval', 'Go (a)', 'Go (b)', '--meaning', 'build it, with (a) wrapped or (b) short rows')
  assert.equal(bare.code, 1, 'of several Go labels one is named as recommended')
  assert.match(bare.out, /^lcw approval with several Go labels needs --recommend <1-2>/)
  assert.equal((await t.cli('approval', 'Go (a)', 'Go (b)', '--recommend', '3')).code, 1)
  const r = await t.cli('approval', 'Go (a)', 'Go (b)', '--recommend', '2', '--meaning', 'build it, with (a) wrapped or (b) short rows')
  assert.equal(r.code, 0)
  assert.deepEqual([t.state().approval.go, t.state().approval.recommend], [['Go (a)', 'Go (b)'], 2])
  assert.equal(t.state().approval.meaning, 'build it, with (a) wrapped or (b) short rows')
  assert.match(fs.readFileSync(`${t.dir}/ledger.md`, 'utf8'), /approval asked: Go \(a\) \/ Go \(b\), recommending Go \(b\)/)
  assert.equal((await t.cli('approval', 'a', 'b', 'c', 'd')).code, 1, 'at most three Go labels')
  assert.equal((await t.cli('approval', 'build it as played back, wrapped')).code, 1, 'a label is short; the meaning goes in --meaning')
  assert.equal((await t.cli('set', 'approval={"go":["Go"],"at":1}')).code, 1, 'only lcw approval sets it')
  await t.cli('stage', 'Spec')
  assert.equal(t.state().approval, null)
  assert.equal((await t.cli('approval')).code, 1, 'only in the Brainstorm')
})
