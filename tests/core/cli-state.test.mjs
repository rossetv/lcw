test('set milestone shows in the state, and a new stage clears it', async () => {
  const t = await begin()
  await t.cli('stage', 'Build')
  assert.equal((await t.cli('set', 'milestone=2 of 3')).code, 0)
  assert.equal(t.state().milestone, '2 of 3')
  await t.cli('stage', 'Review')
  assert.equal(t.state().milestone, null)
})

test('stage, set, status', async () => {
  const t = await begin()
  await t.cli('stage', 'Spec')
  assert.equal(t.state().stage, 'Spec')
  assert.equal(t.state().status, 'running')
  await t.cli('set', 'health=on track', 'spec.requirements=9', 'intent.questionsOpen=2')
  const s = t.state()
  assert.equal(s.health, 'on track')
  assert.equal(s.spec.requirements, 9)
  assert.equal(s.intent.questionsOpen, 2)
  for (const k of ['id=x', 'version=2', 'tasks=[]', 'asks=[]', 'requirements=[]']) assert.equal((await t.cli('set', k)).code, 1)
  assert.equal((await t.cli('stage', 'Nope')).code, 1)
  for (const k of ['status=working', 'stage=Build', 'status.x=1']) {
    const r = await t.cli('set', k)
    assert.equal(r.code, 1)
    assert.match(r.out, /lcw stage, lcw pause, lcw resume, lcw stop or lcw finish/)
  }
  assert.equal(t.state().status, 'running')
  assert.equal(t.state().stage, 'Spec')
  await t.cli('stage', 'Brainstorm')
  assert.equal(t.state().status, 'with-you')
  await t.cli('stage', 'Spec')
  await t.cli('checkpoint', 'write the plan')
  const st = (await t.cli('status')).out
  assert.match(st, /stage: Spec/)
  assert.match(st, /next step: write the plan/)
  assert.match(st, /ledger \(last 15\)/)
  assert.equal(fs.readFileSync(`${t.dir}/checkpoint`, 'utf8'), 'write the plan')
})

