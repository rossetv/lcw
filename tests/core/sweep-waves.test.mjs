test('a wave starts beside one still being built, cut from where that wave was cut, and takes it in only once it is built', async () => {
  const t = await hunting()
  await t.cli('wave', 'add', '1', '1')
  await t.start()
  const wt1 = t.wt
  const cut = git(wt1, 'rev-parse', 'HEAD')
  await t.cli('stage', 'Build')
  commit(wt1, 'b.txt', 'half built\n')
  const r = await t.start()
  assert.equal(r.code, 0, r.out)
  const wt2 = t.wt
  const at = async (n, ...a) => await t.cli(...a, '--wave', String(n))
  const w = (n) => t.state().sweep.waves[n - 1]
  assert.deepEqual([w(2).after, w(2).base], ['lcw/tidy-wave-1', cut])
  assert.equal(fs.existsSync(`${wt2}/b.txt`), false, 'none of wave 1\'s half-built work')
  commit(wt2, 'e.txt', 'wave 2 fix\n')
  const files = (await t.cli('wave', 'files')).out
  assert.match(files, /^ {2}b\.txt \(wave 1\)$/m)
  assert.match(files, /^ {2}e\.txt \(wave 2\)$/m)
  const head2 = git(wt2, 'rev-parse', 'HEAD')
  assert.equal((await at(2, 'wave', 'take')).code, 1, 'nothing to take in while wave 1 is unbuilt')
  assert.equal(git(wt2, 'rev-parse', 'HEAD'), head2)
  assert.equal((await at(2, 'stage', 'Build')).code, 0)
  assert.equal((await at(2, 'stage', 'Review')).code, 0, 'its review range is its own while wave 1 is unbuilt')
  assert.doesNotMatch((await at(2, 'wave', 'take')).out, /go on to Review/, 'wave 2 is in Review already')
  assert.match((await t.cli('status')).out, /review range: git diff lcw\/tidy-wave-1\.\.\.lcw\/tidy-wave-2/)
  assert.equal(git(t.repo, 'diff', '--name-only', 'lcw/tidy-wave-1...lcw/tidy-wave-2'), 'e.txt')
  const built = commit(wt1, 'c.txt', 'the rest\n')
  assert.equal((await at(1, 'stage', 'Review')).code, 0)
  const held = await at(2, 'stage', 'Ship')
  assert.equal(held.code, 1, 'wave 1 is built now, so wave 2 takes it in before it goes on')
  assert.match(held.out, /lcw wave take --wave 2/)
  assert.equal((await at(2, 'wave', 'take')).code, 0)
  assert.equal(git(wt2, 'rev-parse', 'HEAD^2'), built, 'a merge commit of wave 1\'s tip')
  assert.equal(fs.existsSync(`${wt2}/b.txt`), true)
  assert.equal(git(t.repo, 'diff', '--name-only', 'lcw/tidy-wave-1...lcw/tidy-wave-2'), 'e.txt', 'the range is still wave 2\'s own work')
  assert.equal((await at(2, 'stage', 'Ship')).code, 0)
})

test('a wave cut from a built wave goes on to Review while an older wave is still being built, and takes that one in through the wave before once it is built', async () => {
  const t = await hunting()
  await t.cli('wave', 'add', '1', '1', '1')
  const at = async (n, ...a) => await t.cli(...a, '--wave', String(n))
  await t.start()
  const wt1 = t.wt
  await at(1, 'stage', 'Build')
  commit(wt1, 'b.txt', 'half built\n')
  await t.start()
  commit(t.wt, 'e.txt', 'wave 2 fix\n')
  await at(2, 'stage', 'Build')
  await at(2, 'stage', 'Review')
  assert.equal((await t.start()).code, 0)
  commit(t.wt, 'f.txt', 'wave 3 fix\n')
  await at(3, 'stage', 'Build')
  const review = await at(3, 'stage', 'Review')
  assert.equal(review.code, 0, review.out)
  commit(wt1, 'c.txt', 'the rest\n')
  await at(1, 'stage', 'Review')
  const held = await at(3, 'stage', 'Ship')
  assert.equal(held.code, 1, 'wave 1 is built now, and reaches wave 3 only through wave 2')
  assert.match(held.out, /lcw wave take --wave 3/)
  assert.match((await at(3, 'wave', 'take')).out, /lcw wave take --wave 2 first/)
  assert.equal((await at(2, 'wave', 'take')).code, 0)
  assert.equal((await at(3, 'wave', 'take')).code, 0)
  assert.equal(fs.existsSync(`${t.wt}/c.txt`), true)
  assert.equal((await at(3, 'stage', 'Ship')).code, 0)
})

test('a third wave started beside two still being built is cut from where the first of them was cut', async () => {
  const t = await hunting()
  await t.cli('wave', 'add', '1', '1', '1')
  await t.start()
  const cut = git(t.wt, 'rev-parse', 'HEAD')
  commit(t.wt, 'b.txt', 'one\n')
  await t.start()
  commit(t.wt, 'e.txt', 'two\n')
  const r = await t.start()
  assert.equal(r.code, 0, r.out)
  assert.deepEqual(t.state().sweep.waves.map((x) => x.base), [cut, cut, cut])
  assert.equal(t.state().sweep.waves[2].after, 'lcw/tidy-wave-2')
  const line = fs.readFileSync(`${t.dir}/ledger.md`, 'utf8').trim().split('\n').filter((l) => /wave 3 started/.test(l)).at(-1)
  assert.match(line, /beside waves 1, 2\b/, 'it names the waves still being built')
  assert.match(line, /cut from where wave 1 was cut/, 'and the wave they were cut from')
  assert.ok(line.includes(cut), 'at the commit it was cut from')
})

test('a wave takes in what the wave before it changed since it started, before its own review', async () => {
  const t = await overlapping()
  commit(t.wt2, 'e.txt', 'wave 2 fix\n')
  const fix = commit(t.wt1, 'c.txt', 'review fix\n')
  const r = await t.at(2, 'stage', 'Review')
  assert.equal(r.code, 1)
  assert.match(r.out, /wave take/)
  assert.equal(t.w(2).stage, 'Build')
  assert.equal((await t.at(2, 'wave', 'take')).code, 0)
  assert.equal(git(t.wt2, 'rev-parse', 'HEAD^2'), fix, 'a merge commit of wave 1\'s tip')
  assert.equal((await t.at(2, 'stage', 'Review')).code, 0)
  assert.deepEqual([t.w(2).stage, t.w(2).round], ['Review', 1])
  await t.at(2, 'wave', 'round')
  assert.equal(t.w(2).round, 2)
  assert.equal((await t.at(2, 'wave', 'step', 'final checks')).code, 1, 'final checks are a step of Ship')
  assert.equal((await t.at(2, 'wave', 'step', 'closures')).code, 0)
  assert.equal(t.w(2).step, 'closures')
})

test('a take-in that conflicts is undone, and names the worktree and the branch to resolve it in', async () => {
  const t = await overlapping()
  commit(t.wt2, 'b.txt', 'two\n')
  commit(t.wt1, 'b.txt', 'one, reviewed\n')
  const had = git(t.wt2, 'rev-parse', 'HEAD')
  const r = await t.at(2, 'wave', 'take')
  assert.equal(r.code, 1)
  assert.ok(r.out.includes(t.wt2) && r.out.includes('lcw/tidy-wave-2') && r.out.includes('b.txt'), r.out)
  assert.equal(git(t.wt2, 'rev-parse', 'HEAD'), had)
  assert.equal(git(t.wt2, 'status', '--porcelain'), '')
  assert.match(fs.readFileSync(`${t.dir}/waves/2/ledger.md`, 'utf8'), /conflicts in b\.txt/, 'the wave\'s ledger keeps that a resolution waits')
})

test('an older wave merged straight into a wave in Review is refused at a round and on leaving Review, until the waves between take it in', async () => {
  const t = await three()
  await t.start()
  await t.ok('stage', 'Ship', '--wave', '1')
  await t.ok('stage', 'Review', '--wave', '2')
  await t.ok('stage', 'Ship', '--wave', '2')
  await t.start()
  await t.ok('stage', 'Build', '--wave', '3')
  await t.ok('stage', 'Review', '--wave', '3')
  commit(t.wt1, 'f.txt', 'checks fix\n')
  git(t.wt, 'merge', '--no-edit', '-q', 'lcw/tidy-wave-1') // a worker's direct merge past wave 2, not lcw wave take
  for (const a of [['wave', 'round'], ['stage', 'Ship']]) {
    const r = await t.cli(...a, '--wave', '3')
    assert.equal(r.code, 1, a.join(' '))
    assert.match(r.out, /wave take --wave 2/)
  }
  assert.deepEqual([t.w(3).stage, t.w(3).round], ['Review', 1])
  await t.ok('wave', 'take', '--wave', '2')
  await t.ok('wave', 'take', '--wave', '3')
  await t.ok('wave', 'round', '--wave', '3')
  await t.ok('stage', 'Ship', '--wave', '3')
})

test('merged as it goes, waves are cut from the sweep\'s branch and are reviewed, checked and shipped in any order with no take-in', async () => {
  const t = await hunting()
  await t.cli('set', 'sweep.prs=merged')
  await t.cli('wave', 'add', '1', '1')
  await t.start()
  const wt1 = t.wt
  commit(wt1, 'b.txt', 'one\n')
  const ok = async (...a) => { const r = await t.cli(...a); assert.equal(r.code, 0, `${a.join(' ')}\n${r.out}`); return r }
  await ok('stage', 'Review')
  const base = git(t.repo, 'rev-parse', 'lcw/tidy')
  assert.equal((await t.start()).code, 0)
  const wt2 = t.wt
  assert.equal(git(wt2, 'rev-parse', 'HEAD'), base, 'cut from the sweep\'s branch, not from wave 1')
  commit(wt2, 'e.txt', 'two\n')
  commit(wt1, 'c.txt', 'wave 1 review fix\n')
  await ok('stage', 'Review', '--wave', '2')
  await ok('stage', 'Ship', '--wave', '1')
  await ok('stage', 'Ship', '--wave', '2')
  await ok('wave', 'step', 'final checks', '--wave', '2')
  await ok('wave', 'step', 'merging', '--wave', '2')
  await ok('wave', 'shipped', '--wave', '2', '--pr', '20')
  assert.equal(git(t.repo, 'rev-parse', 'lcw/tidy'), base, 'the sweep\'s branch follows the default branch, not the waves')
  const ledger = fs.readFileSync(`${t.dir}/ledger.md`, 'utf8')
  assert.ok(!ledger.includes('BYPASS'), ledger)
})

test('final checks run one wave at a time, in wave order, on a head that holds the wave before it', async () => {
  const t = await bothShipping()
  const r = await t.at(2, 'wave', 'step', 'final checks')
  assert.equal(r.code, 1)
  assert.match(r.out, /Wave 1/)
  assert.equal((await t.at(1, 'wave', 'step', 'final checks')).code, 0)
  assert.equal((await t.at(2, 'wave', 'step', 'final checks')).code, 1, 'wave 1\'s are still running')
  assert.equal((await t.at(1, 'wave', 'step', 'merging')).code, 0)
  assert.match((await t.at(2, 'wave', 'step', 'final checks')).out, /wave take/, 'wave 2 lacks wave 1\'s closure')
  await t.at(2, 'wave', 'take')
  assert.equal((await t.at(2, 'wave', 'step', 'final checks')).code, 0)
  assert.deepEqual([t.w(2).step, t.w(2).checked], ['final checks', git(t.wt2, 'rev-parse', 'HEAD')])
})

test('a wave whose head moved during its final checks does not merge until they run again on the settled head', async () => {
  const t = await shipping(1)
  commit(t.wt, 'b.txt', 'fix\n')
  await t.cli('wave', 'step', 'final checks')
  const moved = commit(t.wt, 'c.txt', 'late fix\n')
  assert.equal((await t.cli('wave', 'step', 'merging')).code, 1)
  assert.equal((await t.cli('wave', 'shipped')).code, 1, 'its checks have not passed')
  await t.cli('wave', 'step', 'final checks')
  assert.equal(t.state().sweep.waves[0].checked, moved)
  assert.equal((await t.cli('wave', 'step', 'merging')).code, 0)
  const tip = commit(t.wt, 'd.txt', 'committed while it merges\n')
  assert.equal((await t.cli('wave', 'shipped')).code, 1)
  assert.notEqual(git(t.repo, 'rev-parse', 'lcw/tidy'), tip)
  assert.equal((await t.ship()).code, 0)
  assert.equal(git(t.repo, 'rev-parse', 'lcw/tidy'), tip)
})

test('a repeat of step merging on the head that was checked says it is at merging already and changes nothing', async () => {
  const t = await shipping(1)
  const tip = commit(t.wt, 'b.txt', 'fix\n')
  await t.cli('wave', 'step', 'final checks')
  await t.cli('wave', 'step', 'merging')
  const before = JSON.stringify(t.state().sweep)
  const ledger = fs.readFileSync(`${t.dir}/ledger.md`, 'utf8')
  const r = await t.cli('wave', 'step', 'merging')
  assert.equal(r.code, 0, r.out)
  assert.ok(r.out.includes(tip), r.out)
  assert.equal(JSON.stringify(t.state().sweep), before)
  assert.equal(fs.readFileSync(`${t.dir}/ledger.md`, 'utf8'), ledger)
})

test('waves land in order, and a shipped wave\'s worktree stays as the latest work until a later wave ships', async () => {
  const t = await bothShipping()
  await t.at(1, 'wave', 'step', 'final checks')
  await t.at(1, 'wave', 'step', 'merging')
  await t.at(2, 'wave', 'take')
  await t.at(2, 'wave', 'step', 'final checks')
  await t.at(2, 'wave', 'step', 'merging')
  const r = await t.at(2, 'wave', 'shipped')
  assert.equal(r.code, 1)
  assert.match(r.out, /Wave 1/)
  assert.equal((await t.at(1, 'wave', 'shipped')).code, 0)
  assert.ok(fs.existsSync(t.wt1))
  assert.match((await t.cli('status')).out, /^ {2}review range: git diff lcw\/tidy\.\.\.lcw\/tidy-wave-2$/m, 'wave 2 reads its own changes on top of what landed')
  assert.equal((await t.cli('wave', 'shipped')).code, 0, 'the only open wave')
  assert.deepEqual([fs.existsSync(t.wt1), t.w(1).worktree, fs.existsSync(t.wt2)], [false, null, true])
  assert.notEqual(git(t.repo, 'branch', '--list', 'lcw/tidy-wave-1'), '', 'its branch stays')
  assert.equal(git(t.repo, 'rev-parse', 'lcw/tidy'), git(t.wt2, 'rev-parse', 'HEAD'))
  assert.match((await t.cli('status')).out, new RegExp(`^latest work: ${t.wt2}$`, 'm'))
})
