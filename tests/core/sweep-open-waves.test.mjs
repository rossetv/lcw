test('a sweep from before waves kept their own records has its running wave\'s stage, lists and worktree moved onto it by the next change', async () => {
  const t = await hunting()
  const wt = tmp('old')
  t.edit((s) => {
    s.sweep.waves = [{ n: 1, fixes: 2, status: 'shipped', branch: 'lcw/tidy-wave-1', pr: 4, merged: false, dropped: 0, fixed: 2 }, { n: 2, fixes: 2, status: 'running', branch: 'lcw/tidy-wave-2', pr: null, merged: false, dropped: 0 }]
    Object.assign(s, { stage: 'Review', stageSince: 1234, worktree: wt, base: 'abc', milestone: '1 of 1', plan: { tasks: 2, atOnce: 2, models: {} } })
    s.tasks = [{ id: 'T1', title: 'one', status: 'done' }]
    s.requirements = [{ id: 'F1', name: 'fix', status: 'todo' }]
  })
  assert.match((await t.cli('status')).out, /waves\/2\/plan.md/, 'status shows the wave as it will be')
  assert.equal(t.state().sweep.waves[1].stage, undefined, 'status changes nothing')
  assert.equal((await t.cli('req', 'F1', 'pass')).code, 0)
  const s = t.state()
  const w = s.sweep.waves[1]
  assert.deepEqual([w.stage, w.stageSince, w.round, w.worktree, w.base, w.after, w.milestone, w.plan.tasks], ['Review', 1234, 1, wt, 'abc', 'lcw/tidy', '1 of 1', 2])
  assert.deepEqual([w.tasks.map((x) => x.id), w.requirements.map((x) => x.status)], [['T1'], ['pass']])
  assert.deepEqual([s.tasks, s.requirements, s.worktree, s.stage], [[], [], null, 'Review'])
  assert.equal(s.sweep.waves[0].stage, undefined, 'a shipped wave is left as it was')
})

test('a shipped wave held for its merge is not the default wave: run-level commands act on the run, and a new wave on itself', async () => {
  const t = await hunting()
  await t.cli('set', 'sweep.prs=merged')
  await t.cli('wave', 'add', '1')
  await t.start()
  await t.cli('stage', 'Ship')
  commit(t.wt, 'b.txt', 'fix\n')
  assert.equal((await t.ship('--pr', '5')).code, 0)
  assert.equal((await t.cli('stage', 'Hunt')).code, 0, 'wave 1 holds for its merge')
  const wave = (n) => t.state().sweep.waves[n - 1]
  assert.equal((await t.cli('ask', 'about the run')).code, 0)
  assert.equal(wave(1).waiting, false)
  assert.equal((await t.cli('ask', 'merge it?', '--wave', '1')).code, 0)
  assert.equal(wave(1).waiting, true, 'still reached with --wave')
  for (const a of [['task', 'add', 'T1', 'one'], ['req', 'add', 'F1', 'fix'], ['set', 'plan.tasks=2']]) assert.equal((await t.cli(...a)).code, 0, a.join(' '))
  assert.deepEqual([t.state().tasks.length, t.state().requirements.length, t.state().plan.tasks, wave(1).tasks.length], [1, 1, 2, 0])

  await t.cli('wave', 'add', '1')
  await t.start()
  assert.equal((await t.cli('task', 'add', 'T1', 'two')).code, 0, 'the running wave, not a refusal for two open')
  assert.equal((await t.cli('stage', 'Build')).code, 0)
  assert.deepEqual([wave(2).tasks.length, wave(2).stage, wave(1).stage], [1, 'Build', 'Ship'])
})

test('a shipped wave drops only its parked fixes, and a fix that passed keeps its count', async () => {
  const t = await shipping(2)
  await t.cli('req', 'add', 'F1', 'one')
  await t.cli('req', 'F1', 'pass')
  await t.cli('req', 'add', 'F2', 'two')
  await t.cli('req', 'F2', 'park')
  commit(t.wt, 'b.txt', 'fix\n')
  await t.ship()
  assert.equal((await t.cli('req', 'F1', 'drop', '--wave', '1')).code, 1)
  assert.match((await t.cli('req', 'F2', 'drop')).out, /--wave 1/, 'with no --wave it names the shipped wave')
  const s = t.state().sweep
  assert.deepEqual([s.waves[0].requirements.map((r) => r.id), s.fixed, s.dropped], [['F1', 'F2'], 1, 0])
  assert.equal((await t.cli('req', 'F2', 'drop', '--wave', '1')).code, 0)
})

test('a sweep whose worktree from before waves had their own sits on its branch ships a wave and moves that worktree with the branch', async () => {
  const t = await hunting()
  const old = `${tmp('old')}/wt`
  git(t.repo, 'worktree', 'add', '-q', old, 'lcw/tidy')
  t.edit((s) => { s.worktree = old })
  await t.cli('wave', 'add', '1')
  await t.start()
  await t.cli('stage', 'Ship')
  const tip = commit(t.wt, 'b.txt', 'fix\n')
  const r = await t.ship()
  assert.equal(r.code, 0, r.out)
  assert.deepEqual([git(t.repo, 'rev-parse', 'lcw/tidy'), git(old, 'rev-parse', 'HEAD'), git(old, 'symbolic-ref', 'HEAD')], [tip, tip, 'refs/heads/lcw/tidy'])
  assert.equal(fs.readFileSync(`${old}/b.txt`, 'utf8'), 'fix\n')
})

