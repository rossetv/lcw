test('a wave with nothing of its own beyond what it took in merges with no final checks, once the wave before it has passed', async () => {
  const t = await overlapping()
  await t.at(1, 'stage', 'Ship')
  await t.at(2, 'stage', 'Review')
  await t.at(2, 'stage', 'Ship')
  const early = await t.at(2, 'wave', 'step', 'merging')
  assert.equal(early.code, 1)
  assert.match(early.out, /Wave 1's final checks have not passed/)
  await t.at(1, 'wave', 'step', 'final checks')
  await t.at(1, 'wave', 'step', 'merging')
  const r = await t.at(2, 'wave', 'step', 'merging')
  assert.equal(r.code, 0, r.out)
  assert.equal((await t.at(1, 'wave', 'shipped')).code, 0)
  assert.equal((await t.at(2, 'wave', 'shipped')).code, 0)
  assert.equal(t.w(2).empty, true)
})

test('a hunt beside open waves reads a fresh worktree of every wave\'s latest work, removed when the sweep finishes', async () => {
  const t = await holdingWithClosure()
  const r = await t.cli('stage', 'Hunt')
  assert.equal(r.code, 0, r.out)
  const latest = fs.realpathSync(`${t.repo}/.claude/worktrees/tidy-latest`)
  assert.match((await t.cli('status')).out, new RegExp(`^latest work: ${latest}$`, 'm'))
  assert.ok(fs.existsSync(`${latest}/d.txt`) && fs.existsSync(`${latest}/e.txt`), 'both waves\' work')
  assert.equal(git(t.repo, 'rev-parse', 'lcw/tidy-wave-2'), git(t.wt2, 'rev-parse', 'HEAD'), 'no wave\'s branch moves')
  assert.equal(git(t.repo, 'rev-parse', `refs/lcw/tidy/hunt-${t.state().sweep.round}`), git(latest, 'rev-parse', 'HEAD'), 'the round\'s commit stays reachable')
  assert.equal((await t.cli('finish')).code, 0)
  assert.ok(!fs.existsSync(latest))
  assert.equal(git(t.repo, 'for-each-ref', 'refs/lcw/'), '')
})
