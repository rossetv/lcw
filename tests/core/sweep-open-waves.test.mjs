test('a wave takes in only the wave before it, once that wave holds every earlier one, so its review range and files are its own', async () => {
  const t = await three()
  await t.start()
  await t.ok('stage', 'Ship', '--wave', '1')
  commit(t.wt, 'e.txt', 'wave 2 fix\n')
  await t.ok('stage', 'Review', '--wave', '2')
  await t.ok('stage', 'Ship', '--wave', '2')
  await t.start()
  const had = commit(t.wt, 'g.txt', 'wave 3 fix\n')
  await t.ok('stage', 'Build', '--wave', '3')
  await t.ok('stage', 'Build', '--wave', '1')
  commit(t.wt1, 'f.txt', 'checks fix\n')
  const r = await t.cli('wave', 'take', '--wave', '3')
  assert.equal(r.code, 1)
  assert.match(r.out, /lcw wave take --wave 2\b/)
  assert.equal(git(t.wt, 'rev-parse', 'HEAD'), had)
  await t.ok('wave', 'take', '--wave', '2')
  await t.ok('wave', 'take', '--wave', '3')
  const range = /^wave 3: .*\n {2}review range: git diff (\S+)$/m.exec((await t.cli('status')).out)[1]
  assert.equal(git(t.repo, 'diff', '--name-only', range), 'g.txt')
  assert.deepEqual((await t.cli('wave', 'files')).out.trim().split('\n').slice(1), ['  b.txt (wave 1)', '  e.txt (wave 2)', '  f.txt (wave 1)', '  g.txt (wave 3)'])
  await t.ok('stage', 'Review', '--wave', '3')
})

